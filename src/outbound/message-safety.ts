/**
 * Outbound message safety (Sections 7.4 check 8, 24.5, 30.3, 44).
 *
 * Everything the model proposes for a channel is re-checked here, on the host,
 * before it can become a Discord send. The model never controls mention
 * behavior or link trust:
 *
 * - Discord mention syntax (`<@id>`, `<@&id>`, `@everyone`, `@here`) is parsed
 *   independently of any model claim and rejected outright — Mneme never
 *   authorizes a ping, so any mention in the proposed text is an injection.
 * - The hard 1,800-character limit is enforced host-side (the schema cap is the
 *   first line of defense; this is the second).
 * - Source links are generated by the host from validated message ids
 *   (Section 30.3: "Links are generated by the host, not trusted from message
 *   content"), capped at three masked links. A Discord jump URL supplied in
 *   model-authored text is rejected rather than trusted or duplicated.
 * - Send options always disable automatic mention parsing and reply pings
 *   (`allowedMentions.parse = []`, `repliedUser = false`), so even an
 *   undiscovered mention token cannot ping.
 *
 * This module is pure: it takes the proposed text and resolved lookups and
 * returns either a sanitized send payload or a rejection. Visibility of cited
 * sources is validated upstream; here we only construct links.
 */

import { messageLink } from '../platform/links.js';
import type { PlatformFormat } from '../platform/types.js';

// Section 24.5 / 23: hard content and citation limits.
export const MAX_MESSAGE_CHARS = 1800;
export const MAX_SOURCE_LINKS = 3;

/**
 * Host-owned identity footer appended to every delivered scheduled notification
 * (Section 12.4). It tells a reader who does not know the bot what the message
 * is and how to act on it. Host-owned: the model never writes it, and the
 * duplicate detector strips it before comparing message bodies.
 */
export const SCHEDULED_NOTIFICATION_FOOTER =
  '_Mneme tracks decisions and open commitments in this server. Reply to this message to update the record._';

/** Remove the host-owned scheduled footer for content comparisons. */
export function stripScheduledFooter(content: string): string {
  return content.endsWith(SCHEDULED_NOTIFICATION_FOOTER)
    ? content.slice(0, -SCHEDULED_NOTIFICATION_FOOTER.length).trimEnd()
    : content;
}

/** A host-constructed, trusted source link (Section 30.3). */
export interface MessageLink {
  messageId: string;
  channelId: string;
  /** Trusted guild-scoped jump URL, built by the host. */
  url: string;
  /** Masked markdown rendering of the link (Section 24.5 "masked source links"). */
  masked: string;
}

/**
 * Resolve a cited message id to the channel a host-built link must point at.
 * Existence/visibility is checked upstream; this only needs the channel.
 */
export interface SourceLinkContext {
  resolveChannelId: (messageId: string) => string | undefined;
  /** Optional trusted display label, for example `#eng · 2026-08-23`. */
  resolveLabel?: (messageId: string) => string | undefined;
}

const INLINE_CITATION_MARKER = /\[\[cite:([A-Za-z0-9._:-]{1,64})\]\]/gu;
const INLINE_CITATION_PREFIX = '[[cite:';

function safeSourceLabel(value: string | undefined): string {
  if (!value) return 'source';
  const normalized = value
    // Control characters must not survive into a host-generated Markdown label.
    // oxlint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f]/gu, ' ')
    .replace(/[@[\]()<>{}\\`*_~|]/gu, '')
    .replace(/\s+/gu, ' ')
    .trim()
    .slice(0, 64);
  return normalized.length > 0 ? normalized : 'source';
}

// Extract broadly, then let the WHATWG parser perform the same special-URL
// normalization a browser does. The lookahead deliberately finds every scheme
// start, even when a preceding URL and Markdown punctuation form one greedy raw
// token; otherwise `[safe](https://example)[source](https://discord...)` could
// hide the second destination. A regex over only the raw spelling is also
// insufficient: backslashes become path separators and the final `@` owns
// userinfo parsing.
const HTTP_URL_CANDIDATE = /(?=(https?:[^\s<>"'`]+))/giu;
const PROTOCOL_RELATIVE_URL_CANDIDATE = /(?=(\/\/[^\s<>"'`]+))/gu;
const DISCORD_NATIVE_URL_CANDIDATE = /(?=(discord:[^\s<>"'`]+))/giu;
// Relative destinations can start with an ordinary segment before traversing
// (for example `docs/../../../channels/...`), and WHATWG recognizes encoded
// dot segments such as `%2e%2e`. Capture the whole boundary-started token and
// resolve it instead of trying to strip a few textual prefixes by hand.
const RELATIVE_URL_CANDIDATE = /(?=([^\s<>"'`]+))/gu;
const RELATIVE_URL_BASE = 'https://mneme.invalid/';
const DISCORD_RELATIVE_URL_BASE = 'https://discord.com/';
const ABSOLUTE_URL_SCHEME = /^[a-z][a-z0-9+.-]*:/iu;

// CommonMark decodes character references in link destinations. These named
// ASCII entities can affect an HTTP URL's authority/path syntax; ordinary host
// letters can also be expressed through numeric references, handled below.
const URL_PUNCTUATION_ENTITIES: Readonly<Record<string, string>> = {
  amp: '&',
  apos: "'",
  bsol: '\\',
  colon: ':',
  commat: '@',
  equals: '=',
  gt: '>',
  lpar: '(',
  lsqb: '[',
  lt: '<',
  num: '#',
  percnt: '%',
  period: '.',
  quest: '?',
  quot: '"',
  rpar: ')',
  rsqb: ']',
  semi: ';',
  sol: '/',
  tab: '',
  newline: '',
};

function decodeMarkdownUrlEntities(content: string): string {
  return content.replace(
    /&(?:#([0-9]{1,7})|#[xX]([0-9a-f]{1,6})|([a-z][a-z0-9]{1,31}));/giu,
    (raw, decimal: string | undefined, hexadecimal: string | undefined, name: string | undefined) => {
      if (name) return URL_PUNCTUATION_ENTITIES[name.toLowerCase()] ?? raw;
      const value = Number.parseInt(decimal ?? hexadecimal ?? '', hexadecimal ? 16 : 10);
      if (
        !Number.isSafeInteger(value)
        || value <= 0
        || value > 0x10ffff
        || (value >= 0xd800 && value <= 0xdfff)
      ) return raw;
      // WHATWG URL preprocessing removes ASCII TAB/LF/CR anywhere in a special
      // URL. Remove entity-produced controls before candidate tokenization so
      // they cannot split the token first.
      if (value === 0x09 || value === 0x0a || value === 0x0d) return '';
      return String.fromCodePoint(value);
    },
  );
}

function normalizeMarkdownUrlSyntax(content: string, preserveLiteralWhitespace = false): string {
  // CommonMark permits a backslash before any ASCII punctuation character in a
  // link destination. Decode entities first so an entity-produced backslash is
  // treated conservatively too.
  return decodeMarkdownUrlEntities(content)
    .replace(
      /\\([\u0021-\u002f\u003a-\u0040\u005b-\u0060\u007b-\u007e])/gu,
      '$1',
    )
    .replace(/[\t\n\r]/gu, preserveLiteralWhitespace ? ' ' : '');
}

function discordHost(hostname: string): boolean {
  const host = hostname.toLowerCase().replace(/\.+$/, '');
  return host === 'discord.com'
    || host.endsWith('.discord.com')
    || host === 'discordapp.com'
    || host.endsWith('.discordapp.com');
}

function normalizeRootedPath(pathname: string): string {
  const rooted = `/${pathname.replace(/[\\/]+/gu, '/').replace(/^\/+/, '')}`;
  try {
    return new URL(rooted, RELATIVE_URL_BASE).pathname;
  } catch {
    return rooted;
  }
}

function discordChannelsPath(pathname: string): boolean {
  let candidate = pathname;
  for (let pass = 0; pass < 3; pass++) {
    // Re-root the path after collapsing slash/backslash ambiguity, then let a
    // special URL parser normalize dot segments. Repeating this after bounded
    // percent-decoding catches encoded separators without interpreting an
    // embedded `//` as a new network authority.
    const normalized = normalizeRootedPath(candidate);
    if (/^\/channels(?:\/|$)/i.test(normalized)) return true;
    try {
      const decoded = decodeURIComponent(normalized);
      if (decoded === normalized) return false;
      candidate = decoded;
    } catch {
      return false;
    }
  }
  return /^\/channels(?:\/|$)/i.test(normalizeRootedPath(candidate));
}

function decodeUrlComponent(candidate: string): string {
  let decoded = candidate;
  for (let pass = 0; pass < 3; pass++) {
    try {
      const next = decodeURIComponent(decoded);
      if (next === decoded) return decoded;
      decoded = next;
    } catch {
      return decoded;
    }
  }
  return decoded;
}

function discordNativeChannelsDestination(parsed: URL): boolean {
  const hostname = decodeUrlComponent(parsed.hostname);
  if (hostname !== '-' && hostname !== '') return false;

  // Native handlers commonly decode and normalize their route after the URL
  // parser. Collapse ambiguous authority/path slash spellings and an optional
  // `-` route host, then apply special-URL dot-segment normalization before
  // checking the channel route.
  const route = parsed.pathname.replace(/^\/+(?:-\/+)?/u, '/');
  try {
    const normalized = new URL(route, RELATIVE_URL_BASE).pathname;
    return discordChannelsPath(normalized);
  } catch {
    return false;
  }
}

function startsRelativeDestination(content: string, index: number, candidate: string): boolean {
  const explicitRelative = /^(?:\/|\.{1,2}\/)/u.test(candidate);
  if (index === 0) return explicitRelative;

  // A root/dot-relative token is URL-like on its own. Ordinary leading
  // segments (`channels/...`, `docs/../../...`) are considered destinations
  // only inside Markdown link/reference syntax, so normal prose beginning with
  // the word "channels" is not rejected.
  if (explicitRelative && /[\s[<{"']/u.test(content[index - 1] ?? '')) return true;

  let cursor = index - 1;
  while (cursor >= 0 && /\s/u.test(content[cursor] ?? '')) cursor -= 1;
  const previous = content[cursor];
  if (previous === ':' && cursor >= 1 && content[cursor - 1] === ']') return true;
  if (previous === '(' && cursor >= 1 && content[cursor - 1] === ']') return true;
  if (previous !== '<') return false;

  // An angle-enclosed relative destination is link syntax only when the angle
  // itself follows an inline-link opener or a reference-definition colon.
  cursor -= 1;
  while (cursor >= 0 && /\s/u.test(content[cursor] ?? '')) cursor -= 1;
  const beforeAngle = content[cursor];
  return (beforeAngle === '(' || beforeAngle === ':')
    && cursor >= 1
    && content[cursor - 1] === ']';
}

const UNKNOWN_NAMED_ENTITY = /&[a-z][a-z0-9]{1,31};/iu;

/**
 * Unknown CommonMark entities are ambiguous only where decoding could change
 * the URL authority, or the first normalized route segment of an already-
 * Discord host. Entities confined to a later fixed route, query, or fragment
 * cannot turn that destination into `/channels`.
 */
function ambiguousEntityCouldFormDiscordJump(candidate: string, base?: string): boolean {
  if (!UNKNOWN_NAMED_ENTITY.test(candidate)) return false;
  const schemeEnd = candidate.indexOf(':');
  const authorityStart = candidate.startsWith('//')
    ? 2
    : candidate.startsWith('//', schemeEnd + 1) ? schemeEnd + 3 : -1;
  if (authorityStart < 0) return true;
  const authorityTail = candidate.slice(authorityStart);
  const authorityEndOffset = authorityTail.search(/[/?#]/u);
  const authority = authorityEndOffset < 0
    ? authorityTail
    : authorityTail.slice(0, authorityEndOffset);
  if (UNKNOWN_NAMED_ENTITY.test(authority)) return true;
  try {
    const parsed = new URL(candidate, base);
    if (!discordHost(parsed.hostname)) return false;
    const segment = firstPathSegment(parsed.pathname);
    return segment !== undefined && UNKNOWN_NAMED_ENTITY.test(segment);
  } catch {
    return true;
  }
}

function firstPathSegment(pathname: string): string | undefined {
  let candidate = pathname;
  for (let pass = 0; pass < 3; pass++) {
    const normalized = normalizeRootedPath(candidate);
    const segment = normalized.split('/').find((part) => part.length > 0);
    if (segment && UNKNOWN_NAMED_ENTITY.test(segment)) return segment;
    try {
      const decoded = decodeURIComponent(normalized);
      if (decoded === normalized) return segment;
      candidate = decoded;
    } catch {
      return segment;
    }
  }
  return normalizeRootedPath(candidate).split('/').find((part) => part.length > 0);
}

/**
 * Resolve one complete relative destination from the Discord origin. This is
 * intentionally origin-rooted: Discord may render or pre-normalize a relative
 * Markdown href before the browser sees the current channel path, and a path
 * that can become `/channels/...` in either case must not be model-authored.
 */
function relativeDestinationIsDiscordJump(candidate: string): boolean {
  if (ABSOLUTE_URL_SCHEME.test(candidate) || candidate.startsWith('//')) return false;
  try {
    const parsed = new URL(candidate, DISCORD_RELATIVE_URL_BASE);
    if (!discordHost(parsed.hostname)) return false;
    if (discordChannelsPath(parsed.pathname)) return true;

    // Unknown CommonMark entities in the first normalized route segment are
    // ambiguous (for example `&cscr;hannels`). Entities in later, fixed routes
    // such as `/docs/&copy;` cannot turn that route into `/channels`.
    const firstSegment = firstPathSegment(parsed.pathname);
    return firstSegment !== undefined && UNKNOWN_NAMED_ENTITY.test(firstSegment);
  } catch {
    return false;
  }
}

/** True when model text contains a URL browsers normalize to a Discord jump. */
function containsDiscordJumpUrl(content: string): boolean {
  const renderedSyntax = normalizeMarkdownUrlSyntax(content);
  for (const match of renderedSyntax.matchAll(HTTP_URL_CANDIDATE)) {
    const candidate = match[1];
    if (!candidate) continue;
    // The full HTML entity catalog includes compatibility characters such as
    // `&dscr;` that WHATWG/IDNA folds to ASCII host letters. Unknown named
    // entities inside a URL are therefore ambiguous and fail closed instead of
    // relying on an incomplete hand-written decoder.
    if (ambiguousEntityCouldFormDiscordJump(candidate)) return true;
    try {
      const parsed = new URL(candidate);
      if (
        (parsed.protocol === 'http:' || parsed.protocol === 'https:')
        && discordHost(parsed.hostname)
        && discordChannelsPath(parsed.pathname)
      ) return true;
    } catch {
      // Invalid URL-like text is not a clickable Discord jump URL.
    }
  }

  for (const match of renderedSyntax.matchAll(PROTOCOL_RELATIVE_URL_CANDIDATE)) {
    const candidate = match[1];
    if (!candidate) continue;
    if (ambiguousEntityCouldFormDiscordJump(candidate, RELATIVE_URL_BASE)) return true;
    try {
      const parsed = new URL(candidate, RELATIVE_URL_BASE);
      if (discordHost(parsed.hostname) && discordChannelsPath(parsed.pathname)) return true;
    } catch {
      // Invalid URL-like text is not a clickable Discord jump URL.
    }
  }

  for (const match of renderedSyntax.matchAll(DISCORD_NATIVE_URL_CANDIDATE)) {
    const candidate = match[1];
    if (!candidate) continue;
    try {
      const parsed = new URL(candidate);
      if (
        parsed.protocol === 'discord:'
        && discordNativeChannelsDestination(parsed)
      ) return true;
    } catch {
      // Invalid URL-like text is not a clickable Discord jump URL.
    }
  }

  // Preserve literal line boundaries here. CommonMark reference definitions
  // allow the destination on the next line; deleting that newline could merge
  // a terminal `/channels` destination with the following reference label.
  const relativeSyntax = normalizeMarkdownUrlSyntax(content, true);
  for (const match of relativeSyntax.matchAll(RELATIVE_URL_CANDIDATE)) {
    const candidate = match[1];
    const index = match.index;
    if (
      !candidate
      || index === undefined
      || !startsRelativeDestination(relativeSyntax, index, candidate)
    ) {
      continue;
    }
    if (relativeDestinationIsDiscordJump(candidate)) return true;
  }
  return false;
}


/**
 * Construct at most {@link MAX_SOURCE_LINKS} trusted masked source links from
 * cited message ids. Links are built solely from the resolved channel and the
 * run's guild — never from URLs the model placed in the message text. A message
 * id that cannot be resolved to a channel contributes no link (its existence and
 * visibility are validated upstream). When the run has no guild
 * (DM context) no guild-scoped link can be built, so an empty list is returned.
 */
export function buildSourceLinks(
  guildId: string | null,
  messageIds: readonly string[],
  ctx: SourceLinkContext,
): MessageLink[] {
  if (guildId === null) return [];
  const links: MessageLink[] = [];
  const seen = new Set<string>();
  for (const id of messageIds) {
    if (links.length >= MAX_SOURCE_LINKS) break;
    if (seen.has(id)) continue;
    const channelId = ctx.resolveChannelId(id);
    if (channelId === undefined) continue;
    seen.add(id);
    const url = messageLink(guildId, channelId, id);
    const label = safeSourceLabel(ctx.resolveLabel?.(id));
    links.push({ messageId: id, channelId, url, masked: `[${label}](${url})` });
  }
  return links;
}

export type InlineCitationResult =
  | { outcome: 'allow'; content: string; unusedLinks: MessageLink[]; markerCount: number }
  | { outcome: 'reject'; reasons: string[] };

/**
 * Replace model-authored citation markers with host-built links. The marker
 * carries only a message ID (`[[cite:<id>]]`); the model never controls the URL
 * or display label. Legacy answers with no markers remain valid and receive a
 * descriptive Sources line from the caller.
 */
export function renderInlineCitations(
  content: string,
  links: readonly MessageLink[],
): InlineCitationResult {
  const byId = new Map(links.map((link) => [link.messageId, link]));
  const used = new Set<string>();
  const reasons: string[] = [];
  let markerCount = 0;
  const rendered = content.replace(INLINE_CITATION_MARKER, (_raw, messageId: string) => {
    markerCount += 1;
    const link = byId.get(messageId);
    if (!link) {
      reasons.push(`inline citation "${messageId}" is not a validated cited source`);
      return '';
    }
    used.add(messageId);
    return link.masked;
  });
  if (rendered.includes(INLINE_CITATION_PREFIX)) {
    reasons.push('message contains a malformed inline citation marker');
  }
  if (reasons.length > 0) return { outcome: 'reject', reasons };
  return {
    outcome: 'allow',
    content: rendered,
    unusedLinks: links.filter((link) => !used.has(link.messageId)),
    markerCount,
  };
}

/** Send-option fragment that guarantees no automatic or reply ping (Sections 24.5, 44). */
export interface SafeSendOptions {
  allowedMentions: {
    /** Empty parse list: Discord will not auto-ping anything found in the text. */
    parse: readonly [];
    /** Never ping the author of a message we reply to. */
    repliedUser: false;
  };
}

/** The always-safe allowed-mentions fragment (no parsing, no reply ping). */
export const SAFE_ALLOWED_MENTIONS: SafeSendOptions = {
  allowedMentions: { parse: [], repliedUser: false },
};

export interface OutboundMessageInput {
  /** The model-proposed message text. */
  content: string;
  /**
   * Message ids to render as host-built masked source links. More than
   * {@link MAX_SOURCE_LINKS} is "over-cited" and rejected (Section 24.5).
   */
  sourceLinkMessageIds?: readonly string[];
  /** The run's guild id (host-pinned); null in a DM context disables link building. */
  guildId: string | null;
  /** The active platform's text conventions; mention syntax is parsed through it. */
  format: PlatformFormat;
}

export interface SanitizedOutbound {
  outcome: 'allow';
  /** Validated content: within the char limit and free of mention syntax. */
  content: string;
  /** Up to three trusted masked source links (possibly fewer if unresolved). */
  sourceLinks: MessageLink[];
  /** Send options with all automatic pings disabled. */
  sendOptions: SafeSendOptions;
}

export interface RejectedOutbound {
  outcome: 'reject';
  /** Redacted reasons (mention kind / limit / count — never message content). */
  reasons: string[];
}

export type SanitizeResult = SanitizedOutbound | RejectedOutbound;

/**
 * Sanitize a proposed outbound message. Returns `reject` for any definite
 * violation — mention injection, an oversized message, or over-citation — so
 * none of those become a send. Otherwise returns the validated content, the
 * host-built source links, and send options that disable every ping path.
 *
 * The two checks compose defensively: parsing rejects any proposal that *tries*
 * to mention, and the empty `parse` list guarantees that even an undiscovered
 * token could not ping. Together they satisfy Section 7.4 check 8.
 */
export function sanitizeOutboundMessage(
  input: OutboundMessageInput,
  ctx: SourceLinkContext = { resolveChannelId: () => undefined },
): SanitizeResult {
  const reasons: string[] = [];

  const mentions = input.format.parseMentions(input.content);
  if (mentions.length > 0) {
    const kinds = [...new Set(mentions.map((m) => m.kind))].sort();
    reasons.push(`message contains unauthorized ${kinds.join('/')} mention(s)`);
  }

  if (input.content.length > MAX_MESSAGE_CHARS) {
    reasons.push(`message is ${input.content.length} characters, over the ${MAX_MESSAGE_CHARS} limit`);
  }

  if (containsDiscordJumpUrl(input.content)) {
    reasons.push('message contains an untrusted Discord source link; cite message ids instead');
  }

  const linkIds = input.sourceLinkMessageIds ?? [];
  if (linkIds.length > MAX_SOURCE_LINKS) {
    reasons.push(
      `message cites ${linkIds.length} source links, over the ${MAX_SOURCE_LINKS} limit`,
    );
  }

  if (reasons.length > 0) return { outcome: 'reject', reasons };

  const sourceLinks = buildSourceLinks(input.guildId, linkIds, ctx);
  return {
    outcome: 'allow',
    content: input.content,
    sourceLinks,
    sendOptions: SAFE_ALLOWED_MENTIONS,
  };
}
